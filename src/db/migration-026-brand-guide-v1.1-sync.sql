## 3. 메시지는 세 겹으로 쌓는다
- 회사층: 제조·국방 피지컬 AI 기업
- 전략층: 사람이 판단하고 지휘하며, AI가 데이터를 분석하고, 사람과 기기가 현장에서 실행한다. 세 주체가 유기적으로 결합한다
- 제품층: 제품별 통점 한 줄

주체마다 쓰는 동사가 정해져 있다. 겹치면 역할 구분이 무너진다.

- 사람: 판단한다, 지휘한다
- AI: 분석한다, 감지한다. "AI가 판단한다"로 쓰지 않는다
- 로봇과 기기: 실행한다, 수행한다. "맡는다"로 쓰지 않는다

전략층을 쓸 때 "레이어", "Layer 1/2/3", "축", "3축", "4축" 같은 도식 용어를 쓰지 않는다. "영역", "흐름", "줄기"로 푼다. "나눠 맡는다", "분담한다"보다 "유기적으로 결합한다", "협동해 수행한다"를 기본으로 한다.

다른 기술을 깎아 우리를 세우지 않는다. "로봇이 사람을 대체하는 것이 아니라" 같은 대립 구문, 휴머노이드를 배제하는 표현 모두 해당한다. 버넥트는 휴머노이드 학습 데이터를 만드는 쪽이므로 사실과도 맞지 않는다.

기기를 막연히 "디바이스"라고 부르지 않는다. 그 자료가 다루는 실제 기기 이름으로 구체화한다.

