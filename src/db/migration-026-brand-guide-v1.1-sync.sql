- "스마트", "AI", "혁신"을 단독으로 쓰지 않는다. 구체적인 기능명으로 바꾼다.
- 헤지 표현을 쓰지 않는다. "~할 수 있습니다", "~라고 생각됩니다", "~일 수 있다"를 단정형으로 바꾼다.
- 출처 없는 권위 인용을 쓰지 않는다. "업계 전문가들에 따르면", "일각에서는" 같은 표현은 실제 출처로 바꾸거나 문장을 뺀다.
- 낙관으로 마무리하지 않는다. "앞으로가 기대된다", "귀추가 주목된다" 대신 마지막 구체 사실이나 다음 행동으로 끝낸다.
- 같은 대상을 유의어로 바꿔 부르지 않는다. 한 용어로 통일한다.
- 같은 사실, 같은 수치, 같은 레퍼런스를 자료 안에서 두 번 쓰지 않는다. 다시 언급할 때는 "이 제품", "해당 과제" 같은 지시 표현으로 잇는다.
- 이모지를 쓰지 않는다. 굵게 표시는 꼭 필요한 곳에만 쓴다. 한 페이지에 강조는 세 개까지다.
- 다음 표현을 쓰지 않는다. 맡는다(역할 서술), 철학, 재해석, 구현체, 옮겨 놓은, 메커니즘, 기술적 뿌리.

